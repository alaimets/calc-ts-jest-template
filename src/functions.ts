export function multiply(num1: number, num2: number): number {
    return num1 * num2;
}

export function calculatePercentage(num1: number, num2: number): number {
    return num1 / num2 * 100;
}

export function isEven(num: number): boolean {
    return num % 2 === 0;
}

export function compareStrings(string1: string, string2: string): boolean {
    return string1 === string2;
}

export function isPositive(num: number): boolean {
    return num > 0;
}